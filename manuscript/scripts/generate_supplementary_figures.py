"""Write a LaTeX catalogue that renders every generated supplementary figure."""

from __future__ import annotations

import argparse
from pathlib import Path

GENERATED_FAMILIES = (
    "point_",
    "counts_",
    "brier_",
    "crps_",
    "precision_recall_",
    "reliability_",
    "margin_intensity_",
    "margin_probabilistic_",
)
LEGACY_FIGURES = {"brier_zero_miss_all.png"}


def write_catalogue(figures_dir: Path, output: Path) -> int:
    """Write one full-width figure environment for each PNG in figures_dir."""
    figures = sorted(
        figure
        for figure in figures_dir.glob("*.png")
        if figure.name.startswith(GENERATED_FAMILIES) and figure.name not in LEGACY_FIGURES
    )
    lines = ["% Generated by manuscript/scripts/generate_supplementary_figures.py", ""]
    for index, figure in enumerate(figures, start=1):
        relative_path = f"fig/{figure.name}"
        label = f"fig:supp-{index:03d}"
        caption = figure.stem.replace("_", " ")
        lines.extend(
            [
                "\\clearpage",
                "\\begin{figure}[p]",
                "\\centering",
                f"\\includegraphics[width=0.96\\linewidth]{{{relative_path}}}",
                f"\\caption{{Supplementary Figure S{index}: {caption}.}}",
                f"\\label{{{label}}}",
                "\\end{figure}",
                "",
            ]
        )
    output.write_text("\n".join(lines))
    return len(figures)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--figures-dir", type=Path, default=Path("manuscript/fig"))
    parser.add_argument("--output", type=Path, default=Path("manuscript/supplementary_figures.tex"))
    args = parser.parse_args()
    count = write_catalogue(args.figures_dir, args.output)
    print(f"Wrote {count} supplementary figures to {args.output}")


if __name__ == "__main__":
    main()
